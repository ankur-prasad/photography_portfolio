export interface PrintGeometry {
  centre: Vec3;
  right: Vec3;
  up: Vec3;
  normal: Vec3;
  /** outer half-extents of the whole assembly, metres */
  halfW: number;
  halfH: number;
}

/** Resolve a DetailView against the configured print's real geometry. */
export function detailShot(v: DetailView, g: PrintGeometry): Shot {
  const focus: Vec3 = [0, 0, 0];
  const dir: Vec3 = [0, 0, 0];
  const axes: [Vec3, number, number][] = [
    [g.right, v.focusAt[0] * g.halfW, v.dir[0]],
    [g.up, v.focusAt[1] * g.halfH, v.dir[1]],
    [g.normal, v.focusAt[2], v.dir[2]],
  ];
  for (const [axis, focusAmt, dirAmt] of axes) {
    for (let i = 0; i < 3; i++) {
      focus[i] += axis[i] * focusAmt;
      dir[i] += axis[i] * dirAmt;
    }
  }
  for (let i = 0; i < 3; i++) focus[i] += g.centre[i];
  return { p: 0, focus, dir, dist: v.dist + v.distPerHalfW * g.halfW, fov: v.fov };
}


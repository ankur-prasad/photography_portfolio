/* ---------------------------------------------------------- close-ups ------
   Per-finish detail shots, the way a print lab photographs its products: the
   corner where the mitre and the mount read, the edge where thickness and
   float-mounting read, the surface. Generated from the actual configured print
   rather than shot from a sample, so what you inspect is your photograph at the
   size and finish you picked.

   Positions are expressed in the print's own basis — (right, up, normal) in
   units of its HALF width/height — so a shot frames the same feature whether
   the print is 20 cm or 90 cm. detailShot() resolves them to world space.        */

export interface DetailView {
  key: string;
  label: string;
  /** focus point: multiples of half-width, half-height, and metres along normal */
  focusAt: [number, number, number];
  /** camera direction from the focus, in the same basis (normalised later) */
  dir: [number, number, number];
  /** metres back from the focus */
  dist: number;
  /** extra distance per metre of the print's half-width, so a 20 cm print and a
   *  90 cm one frame the same feature at a similar apparent size. A fixed
   *  distance put the camera inside a large print and filled the shot with
   *  photograph instead of product. */
  distPerHalfW: number;
  fov: number;
}

